function FSC:GetLanguage()
    local storage = self.storage or FreeSpellCooldownsDB
    return type(storage) == "table" and storage.language == "en" and "en" or "cs"
end

function FSC:T(text)
    if self:GetLanguage() == "en" then return English[text] or text end
    return text
end

local function SetDialogTextFont(text)
    local path, size, flags = text:GetFont()
    FSC:SetCzechFont(text)
    return function()
        if path then text:SetFont(path, size, flags or "") end
    end
end

local function SetDialogButtonFont(button)
    local restoreText = SetDialogTextFont(button:GetFontString())
    local normal, highlight, disabled = button:GetNormalFontObject(),
        button:GetHighlightFontObject(), button:GetDisabledFontObject()
    if not (normal and highlight and disabled) then return restoreText end

    FSC:SetButtonFont(button)
    return function()
        button:SetNormalFontObject(normal)
        button:SetHighlightFontObject(highlight)
        button:SetDisabledFontObject(disabled)
        restoreText()
    end
end

local function RestoreDialogFonts(dialog)
    local restorers = dialogFontRestorers[dialog]
    if not restorers then return end
    dialogFontRestorers[dialog] = nil
    for _, restore in ipairs(restorers) do restore() end
end

local function SetDialogFonts(dialog)
    RestoreDialogFonts(dialog)
    local restorers = {}
    local text = dialog.GetTextFontString and dialog:GetTextFontString() or dialog.Text
    if text then table.insert(restorers, SetDialogTextFont(text)) end
    for index = 1, 2 do
        local button = dialog.GetButton and dialog:GetButton(index) or dialog["Button" .. index]
        if button and button:GetFontString() then
            table.insert(restorers, SetDialogButtonFont(button))
        end
    end
    dialogFontRestorers[dialog] = restorers
end

function FSC:RequestLanguageChange(language)
    if language ~= "en" and language ~= "cs" then return end
    if not self.storage or self:GetLanguage() == language or not self:CanEdit() then return end
    local reload = C_UI and C_UI.Reload or ReloadUI
    if not reload then return end

    StaticPopupDialogs[CONFIRM_LANGUAGE] = {
        text = language == "en" and self:T("Přepnout do angličtiny? Rozhraní hry se znovu načte.")
            or self:T("Přepnout do češtiny? Rozhraní hry se znovu načte."),
        button1 = self:T("Přepnout"),
        button2 = self:T("Zrušit"),
        timeout = 0,
        whileDead = true,
        hideOnEscape = true,
        OnShow = SetDialogFonts,
        OnHide = RestoreDialogFonts,
        OnAccept = function()
            if self:GetLanguage() == language or not self:CanEdit() then return end
            self:ClearInputFocus()
            self.storage.language = language
            self.storage.languageReloadSelection = {cooldown = self.selectedUID, buff = self.selectedBuffUID}
            reload()
        end,
    }
    StaticPopup_Show(CONFIRM_LANGUAGE)
end
